<#
.SYNOPSIS
    Writes tools\iGWindowsTuner.wsb for the current project location and creates the results folder.
.DESCRIPTION
    Windows Sandbox needs absolute host paths. This script regenerates the .wsb with this
    project's folder (mapped read-only) and a sibling "iGWindowsTuner-SandboxResults" folder (writable).
    It does not start Windows Sandbox; double-click tools\iGWindowsTuner.wsb when you are ready.
    Windows Sandbox must be enabled (Windows features: "Windows Sandbox"); enabling it is your call.
.EXAMPLE
    .\tools\New-SandboxConfig.ps1
#>
[CmdletBinding(SupportsShouldProcess = $true)]
param([string]$ResultsFolder)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
if (-not $ResultsFolder) { $ResultsFolder = Join-Path (Split-Path -Parent $root) 'iGWindowsTuner-SandboxResults' }
if (-not (Test-Path -LiteralPath $ResultsFolder) -and $PSCmdlet.ShouldProcess($ResultsFolder, 'Create results folder')) {
    $null = New-Item -ItemType Directory -Path $ResultsFolder -Force
}
$esc = { param($s) [System.Security.SecurityElement]::Escape($s) }
$xml = @"
<Configuration>
  <!-- iG Windows Tuner end-to-end test in Windows Sandbox (generated by tools\New-SandboxConfig.ps1). -->
  <VGpu>Disable</VGpu>
  <Networking>Enable</Networking>
  <MemoryInMB>4096</MemoryInMB>
  <MappedFolders>
    <MappedFolder>
      <HostFolder>$(& $esc $root)</HostFolder>
      <SandboxFolder>C:\iGWindowsTuner</SandboxFolder>
      <ReadOnly>true</ReadOnly>
    </MappedFolder>
    <MappedFolder>
      <HostFolder>$(& $esc $ResultsFolder)</HostFolder>
      <SandboxFolder>C:\SandboxResults</SandboxFolder>
      <ReadOnly>false</ReadOnly>
    </MappedFolder>
  </MappedFolders>
  <LogonCommand>
    <Command>powershell.exe -NoProfile -ExecutionPolicy Bypass -File C:\iGWindowsTuner\tools\Invoke-SandboxTest.ps1 -ResultsPath C:\SandboxResults</Command>
  </LogonCommand>
</Configuration>
"@
$wsb = Join-Path $PSScriptRoot 'iGWindowsTuner.wsb'
if ($PSCmdlet.ShouldProcess($wsb, 'Write sandbox configuration')) { [System.IO.File]::WriteAllText($wsb, $xml, (New-Object System.Text.UTF8Encoding($false))) }
Write-Output "Wrote $wsb (results: $ResultsFolder). Double-click it to start the test; read summary.txt in the results folder afterwards."
